// The German catalog. Every key of `en.ts`, in the same order, in German.
//
// THE ENGLISH CATALOG IS THE SOURCE. `en.ts` is where a string is written and
// where the argument for its wording lives; this file is that argument carried
// into another language and nothing else. A key here that says more, or less,
// than its English twin is a bug in this file, not a second opinion about the
// product.
//
// SIE-FORM THROUGHOUT. The application addresses a professional at work on
// their own book, which in German is "Sie" and stays "Sie" even in a status
// line four words long.
//
// GERMAN CLDR HAS `one` AND `other`, and no other category. Every plural in
// `en.ts` is a `one`/`other` pair, so every plural here is one too;
// `messages.plural` falls back to `other` for any category a catalog omits, so
// nothing is missing the day a category is selected that this file has no arm
// for.
//
// THE CHORD SPELLINGS ARE NOT TRANSLATED. `Ctrl`, `Alt`, `Shift` and the four
// Alt+<letter> menu chords name keys the page actually binds -- the letters
// live in `menu-bar.ts` as `key: "f"` and the rest, and `help.test.ts` compares
// this catalog's claim against them. A German spelling here would be a claim
// about a chord nothing listens for.
//
// THE PRODUCT WORDS ARE FIXED, and are the same word every time they appear:
// Szene, Kapitel, Teil, Buch, Manuskript, Gliederung, Schnappschuss,
// Wiederherstellungspunkt, Archiv, Spiegelordner, Notiz, Figurenverzeichnis,
// Bibel, Pseudonym, Fokusmodus, Schreibmaschinenmodus.

